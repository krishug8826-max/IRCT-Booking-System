-- IRCT Booking Demo PostgreSQL schema. Run once in the cloud SQL console.
-- Isolated schema keeps this app separate from other projects in the same PostgreSQL database.
CREATE SCHEMA IF NOT EXISTS irct;
SET search_path TO irct;

CREATE TABLE IF NOT EXISTS userss (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(150) NOT NULL,
 email VARCHAR(180) NOT NULL, username VARCHAR(80) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL,
 phone VARCHAR(30), gender VARCHAR(30), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS bookings (
 pnr VARCHAR(20) PRIMARY KEY, p_names VARCHAR(1000) NOT NULL, t_name VARCHAR(200) NOT NULL,
 t_no VARCHAR(40) NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'CONFIRMED',
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS trains (
 t_no VARCHAR(40) PRIMARY KEY, t_name VARCHAR(200) NOT NULL, source_stn VARCHAR(120) NOT NULL,
 dest_stn VARCHAR(120) NOT NULL, dep_time VARCHAR(80), price NUMERIC(10,2) NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, fname VARCHAR(100) NOT NULL,
 lname VARCHAR(100) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL,
 phone VARCHAR(30), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS flights (
 flight_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, f_name VARCHAR(180) NOT NULL,
 source VARCHAR(120) NOT NULL, destination VARCHAR(120) NOT NULL, departure_time VARCHAR(100),
 price NUMERIC(10,2) NOT NULL DEFAULT 0, seats_available INTEGER NOT NULL DEFAULT 0 CHECK (seats_available >= 0)
);
CREATE TABLE IF NOT EXISTS flight_reservations (
 res_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_email VARCHAR(180) NOT NULL REFERENCES users(email) ON DELETE CASCADE,
 flight_id BIGINT NOT NULL REFERENCES flights(flight_id), passenger_name VARCHAR(200) NOT NULL,
 seat_no VARCHAR(20) NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_bookings_names ON bookings(p_names);
CREATE INDEX IF NOT EXISTS idx_flight_res_user_created ON flight_reservations(user_email, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_trains_route ON trains(source_stn, dest_stn);
CREATE INDEX IF NOT EXISTS idx_flights_route ON flights(source, destination);
